/** Offline evidence verification: no keys, network, models or mutations. */
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile, readdir } from "node:fs/promises";
import { gunzipSync } from "node:zlib";
import { fileURLToPath } from "node:url";
import path from "node:path";

const dir = fileURLToPath(new URL("./", import.meta.url));
const root = path.resolve(dir, "../../..");
const hash = (value) => createHash("sha256").update(value).digest("hex");
const bytes = (file) => readFile(path.join(dir, file));
const json = async (file) => JSON.parse(await bytes(file));
const close = (a, b) => assert.ok(Math.abs(a - b) < 1e-9, `${a} != ${b}`);
const files = (await readdir(dir)).sort();
const hashes = await json("sha256.json");
assert.deepEqual(Object.keys(hashes).sort(), files.filter((f) => f !== "sha256.json"));
for (const [file, expected] of Object.entries(hashes)) assert.equal(hash(await bytes(file)), expected, file);
const plan = await json("plan.json");
const before = await json("before.json");
const after = await json("after.json");
const execution = await json("preparation-execution.json");
const prepared = (await json("preparation.json")).packet;
const preflight = await json("preflight.json");
const review = await json("plan-review.json");
const summary = await json("summary.json");
const previous = JSON.parse(await readFile(path.join(dir, "../2026-10-21-daniel-presence-retest/summary.json"), "utf8"));
const manifest = await json("manifest.json");
const text = gunzipSync(await bytes("provider.ndjson.gz")).toString();
const trace = text.trim().split("\n").map(JSON.parse);
assert.equal(trace.length, 1);
const row = trace[0];
assert.equal(row.kind, "preparation");
assert.equal(row.status, 200);
assert.equal(row.request.model, plan.textModel);
assert.equal(row.request.response_format.json_schema.name, "scene_plan");
assert.ok(row.response.id);
assert.ok(!text.includes('"user_id"') && !text.includes("data:image/"));
assert.equal(plan.baseCommit, "1220c4cf3d6f0c5d5da8e67ba8e1bec76e20553d");
assert.equal(plan.planPromptVersion, "2026-10-21-formless-presence-v2");
assert.equal(plan.repeats, 1);
assert.equal(plan.maximumImageCalls, 3);
assert.equal(plan.maximumPreparationCalls, 2);
assert.deepEqual(plan.styles, ["classical", "watercolor", "icon"]);
assert.equal(plan.subcapUsd, 0.16);
assert.equal(manifest.plannedCalls, 3);
assert.ok(manifest.withinBudget);
for (const [file, expected] of Object.entries(plan.sourceFiles)) assert.equal(hash(await readFile(path.join(root, file))), expected, file);
assert.deepEqual(before.sourceFiles, after.sourceFiles);
for (const snapshot of [before, after]) {
  assert.equal(snapshot.publicMode, "disabled");
  assert.equal(snapshot.paidCalls, 0);
  assert.equal(snapshot.mutations, 0);
  assert.ok(snapshot.status.ready);
  assert.equal(snapshot.status.activeGeneration, 1);
  assert.ok(snapshot.publicCatalog.artStyles.filter((s) => s.id !== "classical").every((s) => !s.available));
  for (const [file, expected] of Object.entries(snapshot.sourceFiles)) assert.equal(hash(await readFile(path.join(root, file))), expected, file);
}
const record = (snapshot, kind, id) => snapshot.records.find((r) => r.kind === kind && r.recordId === id);
for (const old of before.records.filter((r) => r.kind !== "plan")) assert.deepEqual(record(after, old.kind, old.recordId), old);
const oldPlan = record(before, "plan", "daniel-7-9");
const newPlan = record(after, "plan", "daniel-7-9");
assert.notEqual(newPlan.version, oldPlan.version);
assert.ok(after.planHistory.some((r) => r.version === oldPlan.version));
assert.ok(newPlan.inputs.some((i) => i.kind === "prompt" && i.recordId === "scene_plan_formless_presence" && i.version === plan.planPromptVersion));
assert.equal(newPlan.source, "generated");
const returned = JSON.parse(row.response.choices[0].message.content);
const { present, ...fields } = returned;
assert.deepEqual(present, ["the_ancient_of_days", "daniel_prophet_of_babylon"]);
assert.deepEqual(newPlan.payload.entries.map((e) => e.entryId), present);
assert.deepEqual(newPlan.payload.plan, fields);
assert.deepEqual(prepared.prepared.plan.payload, returned);
assert.equal(prepared.packet.planVersion, newPlan.version);
assert.equal(prepared.packet.lookVersion, "1469b2542a3afbf77ed9921c8f727f20");
const canon = prepared.canon.find((c) => c.entryId === "the_ancient_of_days");
assert.equal(canon.hasForm, false);
assert.equal(canon.stageId, "ancient-of-days-light");
assert.ok(row.request.messages[1].content.includes(`- the_ancient_of_days (stage: ${canon.stageId}): ${canon.text}`));
assert.ok(row.request.messages[0].content.includes("Do not repeat prohibited features as denials or substitutes"));
assert.ok(row.request.messages[0].content.includes("describe the unoccupied seat"));
assert.ok(row.request.messages[1].content.includes(`MOMENT (Daniel 7:9): ${prepared.context.moment.text}`));
const work = JSON.parse(await readFile(path.join(root, "works/bible-web/work.json"), "utf8"));
const verse = work.divisions.find((d) => d.key === "daniel").divisions.find((d) => d.key === "7").units.find((u) => u.number === 9);
assert.equal(prepared.context.moment.text, verse.text);
assert.equal(preflight.paidCalls, 0);
assert.equal(preflight.mutations, 0);
assert.deepEqual(preflight.packets.map((p) => p.styleId), plan.styles);
for (const packet of preflight.packets) {
  assert.equal(packet.preparationCalls, 0);
  assert.equal(packet.preparationCostUsd, 0);
  assert.equal(packet.packet.planVersion, newPlan.version);
  assert.equal(packet.packet.lookVersion, prepared.packet.lookVersion);
  assert.equal(packet.promptSha256, hash(packet.prompt));
  assert.ok(packet.prompt.length <= 8000 && packet.quote);
  assert.ok(packet.prompt.includes(canon.text));
  assert.ok(packet.prompt.includes("FORMLESS SUBJECTS (binding depiction constraints"));
  assert.ok(!packet.packet.references.some((r) => r.id.startsWith("the_ancient_of_days:")));
}
assert.equal(review.acceptedForPilot, false);
assert.equal(review.humanAccepted, false);
assert.equal(review.sceneLanguageVerdict, "fail");
assert.equal(review.planVersion, newPlan.version);
assert.equal(review.preparedPlanSha256, hash(JSON.stringify(prepared.prepared.plan)));
assert.ok(fields.primarySubject.includes("enthroned over a seat"));
assert.ok(fields.primarySubject.includes("with no human face or body"));
assert.equal(execution.phase, "preparation");
assert.equal(execution.textCalls, 1);
assert.equal(execution.imageCalls, 0);
assert.equal(execution.imagesAllowed, false);
assert.equal(execution.uncertainUsd, 0);
close(execution.chargedUsd, row.measuredUsageUsd);
close(row.measuredUsageUsd, row.response.usage.cost);
close(prepared.preparationCostUsd, execution.chargedUsd);
assert.equal(prepared.preparationCalls, 1);
assert.ok(!prepared.preparationUsageMissing);
assert.equal(summary.imageCalls, 0);
assert.equal(summary.preparationCalls, 1);
assert.equal(summary.outcome, "plan-review-failed-before-images");
assert.equal(summary.publicActivation, false);
assert.equal(summary.humanAccepted, false);
assert.equal(summary.originalMatrixCompleted, 236);
assert.equal(summary.originalMatrixPlanned, 324);
close(summary.newMeasuredUsd, execution.chargedUsd);
close(plan.evaluationMeasuredBeforeUsd, previous.budgets.evaluationMeasuredUsd);
close(plan.evaluationUncertaintyBeforeUsd, previous.budgets.evaluationUncertaintyUsd);
close(plan.maximumEvaluationWithSubcapAndPriorUncertaintyUsd, plan.evaluationMeasuredBeforeUsd + plan.evaluationUncertaintyBeforeUsd + plan.subcapUsd);
assert.ok(plan.maximumEvaluationWithSubcapAndPriorUncertaintyUsd <= plan.evaluationAuthorizedUsd);
close(summary.budgets.evaluationMeasuredUsd, plan.evaluationMeasuredBeforeUsd + summary.newMeasuredUsd);
close(summary.budgets.evaluationUncertaintyUsd, previous.budgets.evaluationUncertaintyUsd);
close(summary.budgets.evaluationRemainingUsd, 16 - summary.budgets.evaluationMeasuredUsd - summary.budgets.evaluationUncertaintyUsd);
assert.ok(summary.newMeasuredUsd <= plan.subcapUsd);
for (const key of ["preparationMeasuredUsd", "preparationUncertaintyUsd", "smokeMeasuredUsd"]) close(summary.budgets[key], previous.budgets[key]);
assert.ok(!files.includes("images-execution.json") && !files.includes("image-preflight.json") && !files.includes("outputs"));
console.log(`Verified ${Object.keys(hashes).length} artifact hashes, one measured preparation response, retained v2 plan/history, three unexecuted packets, failed plan review and zero image calls.`);
